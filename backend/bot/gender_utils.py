def _lower(s: str) -> str:
    return s.lower().replace("ـ", "").strip()


def guess_gender(first_name: str) -> str:
    """يرجع 'male' / 'female' / 'unknown'"""
    if not first_name:
        return "unknown"
    name = first_name.strip()
    if not name:
        return "unknown"
    # نأخذ أول كلمة فقط
    first = name.split()[0].strip()
    low = _lower(first)
    # نبحث في القوائم الصريحة أولاً (لتجنب تصنيف حمزة/أسامة كإناث)
    if any(_lower(n) == low for n in _MALE):
        return "male"
    if any(_lower(n) == low for n in _FEMALE):
        return "female"
    # نهاية بـ ة → على الأغلب مؤنث (لأن الأسماء الذكرية بـة قليلة ومغطاة أعلاه)
    if first.endswith("ة"):
        return "female"
    return "unknown"
